import { DOCUMENT, inject, Injectable } from '@angular/core';
import { HttpClient, HttpErrorResponse, HttpParams } from '@angular/common/http';
import { firstValueFrom } from 'rxjs';
import { localDay } from '../assignments/event-date';

export type ExportFormat = 'xlsx' | 'docx';

/** Optional filters of the register; days are yyyy-MM-dd in the browser time zone. */
export interface ExportQuery {
  format: ExportFormat;
  municipalityId: number | null;
  from: string;
  to: string;
  language: string;
}

const FILE_PREFIX = 'registro-territori-';

/** Downloads the territory register generated by the server. */
@Injectable({ providedIn: 'root' })
export class ExportApi {
  private readonly http = inject(HttpClient);
  private readonly document = inject(DOCUMENT);

  async download(query: ExportQuery, today: Date = new Date()): Promise<void> {
    const blob = await this.fetch('/api/export/register', toParams(query));
    this.save(blob, `${FILE_PREFIX}${localDay(today)}.${query.format}`);
  }

  /** Official S-13 register (Word) of a service year, built on the template of the given language. */
  async downloadS13(serviceYear: number, language: string): Promise<void> {
    const blob = await this.fetch('/api/export/s13', s13Params(serviceYear, language));
    this.save(blob, `S-13-${serviceYear}-${language}.docx`);
  }

  private async fetch(url: string, params: HttpParams): Promise<Blob> {
    try {
      return await firstValueFrom(this.http.get(url, { params, responseType: 'blob' }));
    } catch (error) {
      throw await withJsonBody(error);
    }
  }

  private save(blob: Blob, fileName: string): void {
    const url = URL.createObjectURL(blob);
    const link = this.document.createElement('a');
    link.href = url;
    link.download = fileName;
    link.click();
    // Revoked later: some browsers start reading the object URL only after click() returns.
    setTimeout(() => URL.revokeObjectURL(url));
  }
}

export function toParams(query: ExportQuery): HttpParams {
  let params = new HttpParams()
    .set('format', query.format)
    .set('timeZone', Intl.DateTimeFormat().resolvedOptions().timeZone)
    .set('language', query.language);
  if (query.municipalityId !== null) {
    params = params.set('municipalityId', query.municipalityId);
  }
  if (query.from) {
    params = params.set('from', query.from);
  }
  return query.to ? params.set('to', query.to) : params;
}

export function s13Params(serviceYear: number, language: string): HttpParams {
  return new HttpParams()
    .set('serviceYear', serviceYear)
    .set('timeZone', Intl.DateTimeFormat().resolvedOptions().timeZone)
    .set('language', language);
}

/** The service year runs from September to August and is named after the year in which it ends. */
export function currentServiceYear(today: Date = new Date()): number {
  return today.getMonth() >= 8 ? today.getFullYear() + 1 : today.getFullYear();
}

/** Blob requests receive ProblemDetails as a Blob: parse it so the error code can be translated. */
async function withJsonBody(error: unknown): Promise<unknown> {
  if (!(error instanceof HttpErrorResponse) || !(error.error instanceof Blob)) {
    return error;
  }
  let body: unknown = null;
  try {
    body = JSON.parse(await error.error.text());
  } catch {
    // Not JSON: keep a null body so the status-based generic message is shown.
  }
  return new HttpErrorResponse({ error: body, status: error.status, statusText: error.statusText, url: error.url ?? undefined });
}
